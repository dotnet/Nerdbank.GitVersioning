// Package stamp constructs Go linker and generated-source version stamps.
package stamp

import (
	"fmt"
	"go/format"
	"strconv"
	"strings"

	"github.com/dotnet/Nerdbank.GitVersioning/go/internal/adapter"
)

const versionPackage = "github.com/dotnet/Nerdbank.GitVersioning/go/version"

// LinkerFlags returns flags that initialize the runtime version package.
func LinkerFlags(info adapter.Info) string {
	values := []struct {
		name  string
		value string
	}{
		{"semVer", info.SemVer},
		{"version", info.Version},
		{"versionHeight", strconv.Itoa(info.VersionHeight)},
		{"gitCommitID", valueOrEmpty(info.GitCommitID)},
		{"gitCommitIDShort", valueOrEmpty(info.GitCommitIDShort)},
		{"gitCommitDate", valueOrEmpty(info.GitCommitDate)},
		{"publicRelease", strconv.FormatBool(info.PublicRelease)},
	}

	flags := make([]string, 0, len(values))
	for _, value := range values {
		flags = append(flags, "-X="+versionPackage+"."+value.name+"="+value.value)
	}

	return strings.Join(flags, " ")
}

// AppendLinkerFlags preserves effective -ldflags from GOFLAGS and the command
// line while adding version stamps to every package-specific setting.
func AppendLinkerFlags(arguments []string, goFlags, flags string) ([]string, error) {
	goFlagArguments, err := splitQuoted(goFlags)
	if err != nil {
		return nil, fmt.Errorf("parse GOFLAGS: %w", err)
	}

	result := []string{"-ldflags=" + flags}
	for _, argument := range goFlagArguments {
		switch {
		case argument == "-ldflags" || argument == "--ldflags":
			return nil, fmt.Errorf("%s in GOFLAGS requires a value joined with =", argument)
		case strings.HasPrefix(argument, "-ldflags="), strings.HasPrefix(argument, "--ldflags="):
			_, value, _ := strings.Cut(argument, "=")
			result = append(result, "-ldflags="+appendFlags(value, flags))
		}
	}

	for index := 0; index < len(arguments); index++ {
		argument := arguments[index]
		if argument == "-args" || argument == "--" {
			result = append(result, arguments[index:]...)
			break
		}

		switch {
		case argument == "-ldflags" || argument == "--ldflags":
			if index+1 >= len(arguments) {
				return nil, fmt.Errorf("%s requires a value", argument)
			}

			result = append(result, argument, appendFlags(arguments[index+1], flags))
			index++
		case strings.HasPrefix(argument, "-ldflags="):
			_, value, _ := strings.Cut(argument, "=")
			result = append(result, "-ldflags="+appendFlags(value, flags))
		case strings.HasPrefix(argument, "--ldflags="):
			_, value, _ := strings.Cut(argument, "=")
			result = append(result, "--ldflags="+appendFlags(value, flags))
		default:
			result = append(result, argument)
		}
	}

	return result, nil
}

// GeneratedSource returns deterministic Go source that registers version
// information from a package linked into the resulting program.
func GeneratedSource(packageName string, info adapter.Info) ([]byte, error) {
	source := fmt.Sprintf(`// Code generated by nbgv-go generate; DO NOT EDIT.

package %s

import nbgvversion %q

func init() {
	nbgvversion.RegisterGenerated(nbgvversion.Info{
		SemVer: %s,
		Version: %s,
		VersionHeight: %d,
		GitCommitID: %s,
		GitCommitIDShort: %s,
		GitCommitDate: %s,
		PublicRelease: %t,
	})
}
`, packageName, versionPackage, strconv.Quote(info.SemVer), strconv.Quote(info.Version), info.VersionHeight, quoteNullable(info.GitCommitID), quoteNullable(info.GitCommitIDShort), quoteNullable(info.GitCommitDate), info.PublicRelease)
	return format.Source([]byte(source))
}

func appendFlags(existing, additional string) string {
	if existing == "" {
		return additional
	}

	return existing + " " + additional
}

func splitQuoted(value string) ([]string, error) {
	var result []string
	for len(value) > 0 {
		value = strings.TrimLeft(value, " \t\n\r")
		if value == "" {
			break
		}

		if value[0] == '"' || value[0] == '\'' {
			quote := value[0]
			end := strings.IndexByte(value[1:], quote)
			if end < 0 {
				return nil, fmt.Errorf("unterminated %c string", quote)
			}

			result = append(result, value[1:end+1])
			value = value[end+2:]
			continue
		}

		end := strings.IndexAny(value, " \t\n\r")
		if end < 0 {
			result = append(result, value)
			break
		}

		result = append(result, value[:end])
		value = value[end:]
	}

	return result, nil
}

func quoteNullable(value *string) string {
	if value == nil {
		return `""`
	}

	return strconv.Quote(*value)
}

func valueOrEmpty(value *string) string {
	if value == nil {
		return ""
	}

	return *value
}
